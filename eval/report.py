"""
Write eval/RESULTS.md from one or more result files.

  python eval/report.py dev hand
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VARIANT = {"v0_baseline": "prototype baseline (retired)", "v1_schema": "schema + enums",
           "v2_evidence": "schema + evidence", "v3_select": "select, then fill"}


def pct(v, d=0):
    return "–" if v is None else f"{v * 100:.{d}f}%"


def table(configs: dict) -> list[str]:
    rows = sorted(configs.items(), key=lambda kv: -kv[1]["aggregate"]["overall"]["f1"])
    out = ["| Model | Pipeline | Accuracy | Precision | F1 | Hallucinations / form | Omission | Median time | Output tokens |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for _, c in rows:
        a, cfg = c["aggregate"], c["config"]
        o = a["overall"]
        name = VARIANT.get(cfg["variant"], cfg["variant"]) + (" + drop unquoted" if cfg.get("drop_ungrounded") else "")
        out.append(f"| `{cfg['model']}`{' (think)' if cfg.get('think') else ''} | {name} | {pct(o['accuracy'], 1)} | "
                   f"{pct(o['precision'], 1)} | {o['f1']:.3f} | {o['hallucinations_per_case']:.1f} | {pct(o['omission_rate'], 1)} | "
                   f"{a['latency_ms']['p50'] / 1000:.0f}s | {a['tokens_per_case']['output']:.0f} |")
    return out


def main(runs: list[str]) -> None:
    lines = ["# Evaluation results", "",
             "Generated by `eval/report.py`. Definitions:",
             "",
             "- **Accuracy**: share of facts stated in the notes that were filled correctly.",
             "- **Precision**: share of filled answers that are correct.",
             "- **Hallucinations / form**: answers filled for questions the notes never address.",
             "- **Omission**: stated facts left empty.",
             ""]
    for run in runs:
        p = ROOT / "results" / f"{run}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        configs = d["configs"]
        n = next(iter(configs.values()))["aggregate"]["n_cases"]
        lines += [f"## Run `{run}` ({n} case{'s' if n != 1 else ''})", "", *table(configs), ""]
        best_name, best = max(configs.items(), key=lambda kv: kv[1]["aggregate"]["overall"]["f1"])
        g = best["aggregate"]["grounding"]
        if g.get("flag_precision") is not None:
            lines += [f"Quote check for `{best_name}`: {pct(g['flag_precision'])} of flagged answers were wrong, "
                      f"and the flag caught {pct(g['flag_recall'])} of all wrong answers.", ""]
        secs = best["aggregate"]["by_section"]
        lines += ["Per section for the best configuration:", "", "| Section | Facts | Accuracy | Hallucination rate |", "|---|---:|---:|---:|"]
        for s, r in sorted(secs.items(), key=lambda kv: -kv[1]["n_gold"]):
            lines.append(f"| {s} | {r['n_gold']} | {pct(r['accuracy'])} | {pct(r['hallucination_rate'], 1)} |")
        lines.append("")
    (ROOT / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1:] or ["dev", "hand"])
